# What firmware/build.sh freezes into the firmware. Paths are relative to
# this file.

# Everything the i75w_rp2350 board normally freezes
include("$(BOARD_DIR)/manifest.py")

# The switch for the info and debug prints in the app, which are under
# `if __debug__:`. True keeps them. False freezes the app with mpy-cross -O1,
# which compiles __debug__ as False and leaves those blocks out entirely,
# so only warnings, errors and the boot messages are printed. -O1 also
# drops `assert` statements (there are none); tracebacks keep their line
# numbers. Modules loaded from the device's filesystem are compiled there,
# by default with __debug__ True. A local rebuild only recompiles changed
# files: after changing _DEBUG, delete build/rp2/frozen_mpy.
_DEBUG = False

# The app. A module with the same name on the device's filesystem is imported
# instead, eg. hw_conf.py for a different panel.
freeze("../src", (
    "bvgdisp.py",
    "assetfiles.py",
    "crashlog.py",
    "font_bvg.py",
    "hw_conf.py",
    "settings.py",
    "web_server.py",
), opt=0 if _DEBUG else 1)

# The files in src/assets/, generated by firmware/mkassets.py
freeze("build", "frozen_assets.py")

# Runs instead of a main.py on the filesystem
freeze(".", "main.py")
