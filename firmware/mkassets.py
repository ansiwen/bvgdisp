"""Generate a Python module with all files in a directory as bytes, to freeze
them into the firmware (see src/assetfiles.py). The keys are the paths
relative to <base>, as the app opens them on the device.

    python3 mkassets.py <output.py> <base> <directory>
"""
import os
import sys


def main(out_path, base, directory):
    paths = []
    for root, dirs, files in os.walk(os.path.join(base, directory)):
        dirs.sort()
        paths += sorted(os.path.join(root, name) for name in files)
    with open(out_path, "w") as out:
        out.write("# Generated by firmware/mkassets.py, don't edit\n")
        out.write("FILES = {\n")
        for path in paths:
            with open(path, "rb") as f:
                data = f.read()
            name = os.path.relpath(path, base).replace(os.sep, "/")
            out.write("    %r: %r,\n" % (name, data))
        out.write("}\n")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
