"""Generate a Python module with the app's data files as bytes, to freeze them
into the firmware (see src/assets.py).

    python3 mkassets.py <output.py> <file>...
"""
import os
import sys


def main(out_path, paths):
    with open(out_path, "w") as out:
        out.write("# Generated by firmware/mkassets.py, don't edit\n")
        out.write("FILES = {\n")
        for path in paths:
            with open(path, "rb") as f:
                data = f.read()
            out.write("    %r: %r,\n" % (os.path.basename(path), data))
        out.write("}\n")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2:])
