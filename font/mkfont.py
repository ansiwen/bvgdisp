#!/usr/bin/env python3
"""Converts font/font_small.py into src/font_bvg.py, as tables of bytes.

Run it after editing font/font_small.py: python3 font/mkfont.py
"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "font_small.py")
OUT = os.path.join(HERE, "..", "src", "font_bvg.py")

HEIGHT = 8
GLYPH_SIZE = 3 + 2 * HEIGHT  # n, LEFT, RIGHT, then each row as 16 bits
ASCII_FIRST, ASCII_END = 32, 127  # the characters with a direct index

HEADER = '''"""The 8px bitmap font used by render_text() in bvgdisp.py.

Generated by font/mkfont.py from font/font_small.py: edit the font there.
These bytes and str constants stay in flash when frozen.

GLYPHS holds GLYPH_SIZE bytes per glyph: n, LEFT, RIGHT, then the HEIGHT
rows, each 16 bits, big-endian; n and the rows are as in font/font_small.py.
For kerning, bit i of LEFT is the leftmost pixel of row i, and bit i of
RIGHT the pixel of row i next to the gap (bit 1 of the row). The index
tables hold glyph number + 1 (0: no glyph) of chr(32 + i) for ASCII, and of
EXTRA[i] for EXTRA_GLYPHS. The BOLD_ tables hold the bold glyph, or else
the regular one.
"""
'''


def load():
    """Return the font dict of SRC, without executing anything"""
    tree = ast.parse(open(SRC, encoding="utf-8").read(), SRC)
    for node in tree.body:
        if isinstance(node, ast.Assign) and node.targets[0].id == "font_small":
            return ast.literal_eval(node.value)
    sys.exit(SRC + ": no font_small")


def check(char, glyph):
    if len(glyph) != 1 + HEIGHT:
        sys.exit("%r: needs n and %d rows" % (char, HEIGHT))
    n = glyph[0]
    if not 1 <= n <= 16:
        sys.exit("%r: n must be 1-16" % char)
    for row in glyph[1:]:
        if not 0 <= row < 1 << n:
            sys.exit("%r: row %s is wider than n=%d" % (char, bin(row), n))


def bytes_literal(data):
    return 'b"' + "".join("\\x%02x" % b for b in data) + '"'


def main():
    font = load()
    if font.pop("fontheight") != HEIGHT:
        sys.exit("fontheight must be %d" % HEIGHT)
    regular, bold = {}, {}
    for key, glyph in font.items():
        check(key, glyph)
        if len(key) == 2 and key[0] == "*":
            bold[key[1]] = glyph
        elif len(key) == 1:
            regular[key] = glyph
        else:
            sys.exit("%r: a key is a character, or * and a character" % key)

    # glyph numbers in the order of font_small.py
    glyphs = []
    numbers = {}
    for key, glyph in font.items():
        numbers[key] = len(glyphs) + 1
        glyphs.append((key, glyph))
    if len(glyphs) > 255:
        sys.exit("more than 255 glyphs")

    def index(chars, bold_tables):
        out = bytearray()
        for c in chars:
            if bold_tables and c in bold:
                out.append(numbers["*" + c])
            else:
                out.append(numbers.get(c, 0))
        return bytes(out)

    ascii_chars = [chr(c) for c in range(ASCII_FIRST, ASCII_END)]
    extra = "".join(sorted(c for c in set(regular) | set(bold)
                           if not ASCII_FIRST <= ord(c) < ASCII_END))

    out = [HEADER]
    out.append("HEIGHT = %d\n" % HEIGHT)
    out.append("GLYPH_SIZE = %d\n" % GLYPH_SIZE)
    out.append("GLYPHS = (\n")
    for key, glyph in glyphs:
        n, rows = glyph[0], glyph[1:]
        left = sum((row >> (n - 1) & 1) << i for i, row in enumerate(rows))
        right = sum((row >> 1 & 1) << i for i, row in enumerate(rows))
        data = bytearray([n, left, right])
        for row in rows:
            data += row.to_bytes(2, "big")
        out.append("    %s  # %d: %s\n" % (bytes_literal(data), numbers[key], repr(key)))
    out.append(")\n")
    out.append("ASCII = %s\n" % bytes_literal(index(ascii_chars, False)))
    out.append("BOLD_ASCII = %s\n" % bytes_literal(index(ascii_chars, True)))
    out.append("EXTRA = %s\n" % repr(extra))
    out.append("EXTRA_GLYPHS = %s\n" % bytes_literal(index(extra, False)))
    out.append("BOLD_EXTRA_GLYPHS = %s\n" % bytes_literal(index(extra, True)))

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(OUT), "with", len(glyphs), "glyphs")


main()
